#!/usr/bin/env python3
"""Summarize uncertainty across independently trained/evaluated runs.

Each run directory must contain per_image_metrics.csv generated by evaluate.py.
Each run should correspond to an independent training seed/checkpoint, not repeated
inference of the same checkpoint. The script averages per-image scores within each
run, then summarizes those run-level means using mean, sample SD, and a t-based 95% CI.
"""

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import t

METRICS = ["psnr_y_db", "ssim_rgb", "mae_rgb", "clip_similarity", "lpips"]
KEYS = ["pair_id", "pair_type"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", nargs="+", required=True, type=Path, help="Run directories containing per_image_metrics.csv")
    parser.add_argument("--out-dir", required=True, type=Path, help="Output directory for uncertainty tables")
    parser.add_argument("--confidence", type=float, default=0.95, help="Confidence level, default 0.95")
    args = parser.parse_args()

    if len(args.runs) < 2:
        raise ValueError("At least two independent run directories are required for uncertainty estimates.")
    if not 0.0 < args.confidence < 1.0:
        raise ValueError("--confidence must be between 0 and 1.")

    run_frames = []
    reference_keys = None
    run_names = []
    for run_dir in args.runs:
        csv_path = run_dir / "per_image_metrics.csv"
        if not csv_path.is_file():
            raise FileNotFoundError(f"Missing {csv_path}")
        frame = pd.read_csv(csv_path)
        missing = [c for c in KEYS + METRICS if c not in frame.columns]
        if missing:
            raise ValueError(f"{csv_path} is missing columns: {missing}")
        keys = frame[KEYS].sort_values(KEYS).reset_index(drop=True)
        if reference_keys is None:
            reference_keys = keys
        elif not reference_keys.equals(keys):
            raise ValueError(
                "Runs do not contain identical pair_id/pair_type rows. "
                "Use the same fixed test set and pairing for every run."
            )
        run_frames.append(frame)
        run_names.append(run_dir.name)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    run_mean_rows = []
    for run_name, frame in zip(run_names, run_frames):
        for pair_type, group in frame.groupby("pair_type", sort=True):
            for metric in METRICS:
                values = group[metric].to_numpy(dtype=float)
                if not np.all(np.isfinite(values)):
                    mean_value = np.nan
                else:
                    mean_value = float(np.mean(values))
                run_mean_rows.append({
                    "run": run_name,
                    "pair_type": pair_type,
                    "metric": metric,
                    "n_images": int(len(values)),
                    "run_mean": mean_value,
                })
    run_means = pd.DataFrame(run_mean_rows)
    run_means.to_csv(args.out_dir / "run_level_means.csv", index=False, float_format="%.10g")

    summary_rows = []
    alpha = 1.0 - args.confidence
    for (pair_type, metric), group in run_means.groupby(["pair_type", "metric"], sort=True):
        vals = group["run_mean"].to_numpy(dtype=float)
        vals = vals[np.isfinite(vals)]
        n = len(vals)
        mean = float(np.mean(vals)) if n else float("nan")
        sd = float(np.std(vals, ddof=1)) if n >= 2 else float("nan")
        if n >= 2:
            se = sd / np.sqrt(n)
            critical = float(t.ppf(1.0 - alpha / 2.0, df=n - 1))
            ci_low = mean - critical * se
            ci_high = mean + critical * se
        else:
            ci_low = float("nan")
            ci_high = float("nan")
        summary_rows.append({
            "pair_type": pair_type,
            "metric": metric,
            "n_runs": int(n),
            "mean_of_run_means": mean,
            "sd_across_runs": sd,
            "confidence_level": args.confidence,
            "ci_low_t": ci_low,
            "ci_high_t": ci_high,
            "note": "CI is based on independent run-level means; use independently trained checkpoints for valid training variability estimates",
        })
    summary = pd.DataFrame(summary_rows)
    summary.to_csv(args.out_dir / "uncertainty_summary.csv", index=False, float_format="%.10g")

    metadata = {
        "runs": [str(p.resolve()) for p in args.runs],
        "n_runs_requested": len(args.runs),
        "confidence_level": args.confidence,
        "interval": "two-sided Student t interval across independent run-level means",
        "aggregation": "mean each metric over test images within each run, then calculate mean and sample SD across runs",
        "warning": "Do not treat repeated inference of one fixed checkpoint as independent training runs.",
    }
    with (args.out_dir / "uncertainty_metadata.json").open("w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)
    print(f"Wrote: {args.out_dir / 'run_level_means.csv'}")
    print(f"Wrote: {args.out_dir / 'uncertainty_summary.csv'}")
    print(f"Wrote: {args.out_dir / 'uncertainty_metadata.json'}")


if __name__ == "__main__":
    main()
